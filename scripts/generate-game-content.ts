// Reads content/games/*.md and writes client/src/data/gameContent.generated.ts: the
// connect-the-words pairs, the cooking shelf, the dishes, and the celebration phrases.
//
// Client-only, unlike PAGE_IDS/PAGES: a round of either game is never sent to the server
// (no lives, no score, no saved progress by design), so there is nothing for the api to
// validate and no api-side generated module.
//
// Run via `make generate-content`, alongside scripts/generate-content.ts.

import {
  GAME_WORD_KEYS,
  type GamePair,
  gamePairAudioUrl,
  loadAllGamePairs,
  loadGamePhrases,
  loadUiSounds,
  travelStops,
  WORDS_FILE,
} from './gameContent.ts';
import {
  assertNoSlugCollisions,
  type ClipClaim,
  loadPages,
  pageClipClaims,
  type Sound,
  soundFileUrl,
} from './content.ts';
import { COLOR_ICON_PREFIX, GAME_COLOR_IDS, OBJECT_ICON_IDS } from '../client/src/GameIcons/iconIds.ts';

const OUT = new URL('../client/src/data/gameContent.generated.ts', import.meta.url);

// Same rationale as scripts/generate-content.ts's assertClipsExist: a missing clip should
// fail the build, not ship a tap-to-play button that plays nothing.
async function assertClipsExist(lists: Record<string, GamePair[]>): Promise<void> {
  const missing: string[] = [];

  for (const [file, pairs] of Object.entries(lists)) {
    for (const pair of pairs) {
      const url = gamePairAudioUrl(pair);
      try {
        await Deno.stat(url);
      } catch {
        missing.push(`  ${file}: "${pair.sv}" -> ${url.pathname}`);
      }
    }
  }

  if (missing.length > 0) {
    throw new Error(
      `missing audio clips for content/games/:\n${missing.join('\n')}\n` +
        'Run `make generate-audio` on macOS, then commit the clips.',
    );
  }
}

// An icon key with no drawing behind it renders nothing at all — GameIcon returns null and
// the card comes up blank, which no type check catches because the key is a string in
// content. The id lists are imported rather than duplicated; see client/src/GameIcons/iconIds.ts.
function assertIconsExist(lists: Record<string, GamePair[]>): void {
  const objects = new Set<string>(OBJECT_ICON_IDS);
  const colors = new Set<string>(GAME_COLOR_IDS);
  const unknown: string[] = [];

  for (const [file, pairs] of Object.entries(lists)) {
    if (file === WORDS_FILE) continue;
    for (const pair of pairs) {
      const known = pair.icon.startsWith(COLOR_ICON_PREFIX)
        ? colors.has(pair.icon.slice(COLOR_ICON_PREFIX.length))
        : objects.has(pair.icon);
      if (!known) unknown.push(`  ${file}: "${pair.sv}" -> ${pair.icon}`);
    }
  }

  if (unknown.length > 0) {
    throw new Error(
      `unknown icons in content/games/:\n${unknown.join('\n')}\n` +
        'Draw it in client/src/GameIcons/GameIcons.tsx and add the id to iconIds.ts, ' +
        `or use one of: ${[...objects, ...[...colors].map((c) => COLOR_ICON_PREFIX + c)].join(', ')}`,
    );
  }
}

// A misnamed effect would 404 on the iPad and be silent, which is indistinguishable from
// "the sound is off" — the whole reason the wiring waited for the files.
async function assertSoundsExist(roles: Record<string, Sound[]>): Promise<void> {
  const missing: string[] = [];

  for (const [role, sounds] of Object.entries(roles)) {
    for (const sound of sounds) {
      try {
        await Deno.stat(soundFileUrl(sound));
      } catch {
        missing.push(`  ${role}: ${sound.audio}`);
      }
    }
  }

  if (missing.length > 0) {
    throw new Error(
      `missing sound effects for content/games/ui-sounds.md:\n${missing.join('\n')}\n` +
        'Drop the file in client/static/media/sfx/ and run `make convert-sfx` on macOS.',
    );
  }
}

const HEADER = '// GENERATED by scripts/generate-game-content.ts from content/games/*.md — do not edit by hand.\n' +
  '// Rerun `make generate-content` (or `make dev` / `make build` / `make check`, which do\n' +
  '// this for you) after changing anything under content/games/.\n\n';

const lists = await loadAllGamePairs();
const phrases = await loadGamePhrases();
const uiSounds = await loadUiSounds();

// The clip namespace is one flat directory shared by topic pages and every game list, so the
// collision check has to span both — and this script is the one that sees both. Without it a
// game pair "hår" quietly plays har.m4a, the "har" from content/sentence.md: the right card,
// the wrong word, and nothing to notice it by.
const gameClaims: ClipClaim[] = Object.entries(lists).flatMap(([file, pairs]) =>
  pairs.map((pair) => ({ sv: pair.sv, source: `games/${file}` }))
);
assertNoSlugCollisions([...pageClipClaims(await loadPages()), ...gameClaims]);

assertIconsExist(lists);
await assertClipsExist(lists);
await assertSoundsExist(uiSounds);

const pairs = lists['connect-pairs.md'] ?? [];
const cooking = lists['cooking.md'] ?? [];
const dishes = lists['dishes.md'] ?? [];
const kitchen = lists['kitchen.md'] ?? [];
const shop = lists['shop.md'] ?? [];
const hotel = lists['hotel.md'] ?? [];
const travel = travelStops(lists['travel.md'] ?? [], pairs, 'games/travel.md');

const wordList = lists[WORDS_FILE] ?? [];
const words = Object.fromEntries(
  GAME_WORD_KEYS.map((key) => {
    const word = wordList.find((w) => w.sv === key);
    if (!word) throw new Error(`games/${WORDS_FILE}: missing "${key}", which a game says`);
    return [key, word.audio];
  }),
);

const uiSoundUrls = Object.fromEntries(
  Object.entries(uiSounds).map(([role, sounds]) => [role, sounds.map((sound) => sound.audio)]),
);

await Deno.writeTextFile(
  OUT,
  `${HEADER}import type { GamePair, TravelStop } from './gameContent';\n\n` +
    `export const GAME_PAIRS: GamePair[] = ${JSON.stringify(pairs, null, 2)};\n\n` +
    `export const COOKING_ITEMS: GamePair[] = ${JSON.stringify(cooking, null, 2)};\n\n` +
    `export const DISHES: GamePair[] = ${JSON.stringify(dishes, null, 2)};\n\n` +
    `export const KITCHEN: GamePair[] = ${JSON.stringify(kitchen, null, 2)};\n\n` +
    `export const SHOP_ITEMS: GamePair[] = ${JSON.stringify(shop, null, 2)};\n\n` +
    `export const HOTEL_GUESTS: GamePair[] = ${JSON.stringify(hotel, null, 2)};\n\n` +
    `export const TRAVEL_STOPS: TravelStop[] = ${JSON.stringify(travel, null, 2)};\n\n` +
    `export const GAME_WORDS = ${JSON.stringify(words, null, 2)} as const;\n\n` +
    `export const GAME_PHRASES: string[] = ${JSON.stringify(phrases, null, 2)};\n\n` +
    `export const UI_SOUNDS: Record<string, string[]> = ${JSON.stringify(uiSoundUrls, null, 2)};\n`,
);

console.log(
  `generated ${pairs.length} pairs, ${cooking.length} ingredients, ${dishes.length} dishes, ` +
    `${kitchen.length} kitchen words, ${shop.length} shop items, ${hotel.length} hotel guests, ` +
    `${travel.length} travel stops, ${wordList.length} game words, ${phrases.length} phrases, ` +
    `${Object.keys(uiSoundUrls).length} ui sound roles -> ${OUT.pathname}`,
);
